const assert=require('node:assert/strict');
const Analytics=require('./dist/analytics.js');
const View=require('./dist/chart-view.js');
const model=Analytics.summarize([{type:'expense',amount:650,date:'2024-02-29',category:'<img src=x onerror=alert(1)>'},{type:'income',amount:500,date:'2024-02-29'}],'2024-02');
const html=View.render(model);
assert.ok(html.includes('data-analytics-view="categories"'));
assert.ok(html.includes('data-analytics-view="weeks"'));
assert.ok(html.includes('category-track'));
assert.ok(html.includes('chart-date-label'));
assert.ok(!View.selection('category',model.categories[0],0).includes('<img'));
assert.ok(View.selection('week',{start:'2024-02-01',end:'2024-02-04',income:1234567,expense:0,net:1234567},0).includes('has-long-values'));
assert.ok(html.includes('&lt;img src=x onerror=alert(1)&gt;'));
assert.ok(!html.includes('<img'));
assert.ok(html.includes('650.00 ฿'));
assert.equal((html.match(/class="chart-week"/g)||[]).length,5);
assert.ok(html.includes('tabindex="0" role="button"'));
assert.ok(html.includes('ดูตัวเลขทุกสัปดาห์'));
assert.ok(!/NaN|Infinity/.test(html));
const many=Analytics.summarize(Array.from({length:30},(_,i)=>({type:'expense',amount:i+0.01,date:'2024-02-29',category:'หมวด '+i})),'2024-02');
assert.equal((View.render(many).match(/class="chart-category"/g)||[]).length,30,'All categories retained');
const empty=View.render(Analytics.summarize([{type:'transfer',amount:100,date:'2024-02-29'}],'2024-02'));
assert.ok(empty.includes('ยังไม่มีรายจ่ายในเดือนนี้'));
assert.ok(empty.includes('ยังไม่มีรายรับหรือรายจ่ายในเดือนนี้'));
assert.ok(!empty.includes('class="chart-week"'));
assert.ok(View.render(Analytics.summarize([{type:'expense',amount:1234567890.12,date:'2024-02-29',category:'ยาว'}],'2024-02')).includes('1,234,567,890.12 ฿'));
console.log('PASS: chart escaping, full values, keyboard semantics, all categories, empty/transfer-only states and finite SVG geometry.');
